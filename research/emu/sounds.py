"""Write game/sounds.py: the machine's sounds as scores of square-wave tones.

The original has one speaker driven on/off by the program. Every sound is a run of tones and pauses, so it is
described exactly by (level, time high, time low, repeats) with times in CPU cycles (75000 per second).
The scores are measured on the ROM running in the emulator.
    python sounds.py
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'game'))
from board import ElecDet, IPS, load_romset

ROMZIP = os.environ.get('ELECDET_ROM', os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'elecdet'))   # the MAME romset (folder or zip)
ALIAS = {'S': 'SUSPECT', 'Q': 'PQ', 'A': 'ACCUSE', 'E': 'ENTER', 'T': 'ENDTURN'}


class Rec:
    def __init__(self):
        self.b = ElecDet(load_romset(ROMZIP))

    def run(self, s): self.b.run(int(s * IPS))

    def key(self, k, capture=None):
        """Press a key; with capture=seconds return the speaker events from key-down on."""
        b = self.b; k = ALIAS.get(k, k)
        b.sound_events = []; c0 = b.cpu.cycles
        b.set_key(k, True); self.run(0.15); b.set_key(k, False); self.run(0.3)
        if capture:
            self.run(capture - 0.45)
            return [(c - c0, lv) for c, lv in b.sound_events]

    def keys(self, s):
        for k in s.split(): self.key(k)

    def number(self, which):
        R = lambda r, c: self.b.cpu.ram[r * 16 + c]
        num = lambda r: R(r, 10) + (10 * R(r, 11) if R(r, 11) < 10 else 0)
        m, v = num(0), num(4)
        return ' '.join(str({'M': m, 'W': next(x for x in range(1, 21) if x not in (m, v))}[which]))


def score(events):
    """[(cycle, level)] -> [(level, high, low, repeats)]; a pause is (0, 0, cycles, 1)."""
    out, t, i = [], 0, 0
    ev = [e for j, e in enumerate(events) if j == 0 or e[1] != events[j - 1][1]]
    if ev and ev[0][1] == 0: ev = ev[1:]
    while i + 1 < len(ev):
        (c_up, lv), (c_down, _) = ev[i], ev[i + 1]
        if c_up > t: out.append((0, 0, c_up - t, 1))
        nxt = ev[i + 2][0] if i + 2 < len(ev) else c_down
        hi, lo = c_down - c_up, nxt - c_down
        if lo > 2000:                                     # a real pause follows: keep it separate
            cell = (lv, hi, 0, 1); t = c_down
        else:
            cell = (lv, hi, lo, 1); t = nxt
        if out and out[-1][:3] == cell[:3]: out[-1] = cell[:3] + (out[-1][3] + 1,)
        else: out.append(cell)
        i += 2
    return out


def length(sc): return sum((hi + lo) * n for _, hi, lo, n in sc)


if __name__ == '__main__':
    S = {}
    r = Rec(); r.b.power_on(); r.b.sound_events = []; c0 = r.b.cpu.cycles
    r.run(3.2); S['power_on'] = score([(c - c0, lv) for c, lv in r.b.sound_events]); r.run(3.5)
    r.keys('3 2'); S['crime'] = score(r.key('E', 6.0))
    r.keys('S ' + r.number('W') + ' E'); r.run(1.5)
    S['bong'] = score(r.key('T', 1.0))
    r.keys('A ' + r.number('W')); S['wrong'] = score(r.key('E', 4.0))
    r.run(1); r.keys('A ' + r.number('W')); S['wrong_last'] = score(r.key('E', 8.0))
    r2 = Rec(); r2.b.power_on(); r2.run(6.5); r2.keys('3 1 E'); r2.run(6)
    r2.keys('A ' + r2.number('M')); S['solved'] = score(r2.key('E', 6.0))
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'game', 'sounds.py')
    with open(out, 'w', newline='\n') as f:
        f.write('"""Sounds of the machine as scores of square-wave tones: (level, cycles high, cycles low, repeats);\n'
                'level 0 is a pause. 75000 cycles per second. Generated by research/emu/sounds.py from measurements."""\n')
        f.write('SOUNDS = {\n')
        for name, sc in S.items():
            f.write('    %r: [' % name)
            for i, cell in enumerate(sc):
                f.write(('\n        ' if i % 8 == 0 else ' ') + '(%d, %d, %d, %d),' % cell)
            f.write('\n    ],\n')
            print('%-11s %4d cells, %.2f s, %d tones' % (name, len(sc), length(sc) / IPS, sum(n for lv, _, _, n in sc if lv)))
        f.write('}\n')
